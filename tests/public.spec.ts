import fs from 'node:fs';
import { expect, test } from '@playwright/test';
const REGIONS = { results: [{ lawd_cd: '11440', name: 'Seoul Mapo' }], query: 'mapo' };
const TRADES = { items: [{ name: 'Fixture Apt', district: 'district', area_m2: 49.97, floor: 19, price_10k: 85500, deal_date: '2026-09-21', build_year: 2005, deal_type: 'type' }], summary: { median_price_10k: 85500, min_price_10k: 85500, max_price_10k: 85500, sample_count: 1 }, query: { asset_type: 'apartment', lawd_cd: '11440', deal_ymd: '202609' }, units: 'Prices are in 10,000 KRW units.', source: 'fixture', proxy: 'k-skill-proxy' };
test('public district search and full fictional flow without model calls', async ({ page }) => {
  const museCalls: string[] = [];
  const errors: string[] = [];
  page.on('request', (r) => { if (r.url().includes('/api/muse')) museCalls.push(r.url()); });
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('pageerror', (e) => errors.push(String(e)));
  await page.route('**/api/housing*', async (r) => {
    const u = new URL(r.request().url());
    if (u.searchParams.get('kind') === 'regions') return r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(REGIONS) });
    return r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(TRADES) });
  });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await expect(page.getByRole('heading', { name: /Try a day|Explore a day/ })).toBeVisible();
  await page.getByRole('heading', { name: /Try a day|Explore a day/ }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results-public/prepare.png' });
  await page.getByLabel(/District search/).fill('mapo');
  await page.getByRole('button', { name: /Search districts/ }).click();
  await page.getByRole('button', { name: /Select · Seoul Mapo/ }).click();
  await expect(page.getByTestId('selected-district')).toContainText('Seoul Mapo');
  await page.getByLabel(/Deal month/).fill('2026-09');
  await page.getByRole('button', { name: /Load past sales/ }).click();
  await expect(page.getByText(/past sales for 202609/)).toBeVisible();
  await expect(page.getByText(/85500 = KRW 855,000,000|10,000 KRW/)).toBeVisible();
  await page.getByRole('button', { name: 'Enter simulation', exact: true }).click();
  await expect(page.getByRole('heading', { name: /A day in Solan Village|Visit checks/ })).toBeVisible();
  await expect(page.getByText(/District plan: Seoul Mapo · 202609/)).toBeVisible();
  await page.getByLabel('Observation', { exact: true }).fill('public demo note');
  await page.getByRole('button', { name: 'Add note', exact: true }).click();
  await expect(page.getByText('Saved.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /field prompts/i }).click();
  await expect(page.getByText(/What would you check|Where does|What remains/).first()).toBeVisible();
  expect(museCalls.length).toBe(0);
  await page.getByRole('heading', { name: /A day in Solan Village|Visit checks/ }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results-public/virtual-visit.png' });
  await page.getByRole('button', { name: 'Night', exact: true }).first().click();
  await expect(page.locator('.scene-readout')).toContainText('Night');
  await page.getByRole('button', { name: 'Save this scenario', exact: true }).click();
  await page.getByRole('radio', { name: /Life scenarios/ }).click();
  await page.getByLabel(/Home price/).fill('900');
  await page.getByRole('button', { name: /Save scenario snapshot/ }).click();
  await expect(page.locator('.hs-curve')).toBeVisible();
  await page.getByRole('tab', { name: 'Moonlight House' }).click();
  await page.getByRole('radio', { name: /Life scenarios/ }).click();
  await expect(page.getByLabel(/Home price/)).toHaveValue('855');
  await page.getByLabel(/Home price/).fill('800');
  await page.getByRole('button', { name: /Save scenario snapshot/ }).click();
  await page.getByRole('tab', { name: 'Sunlit House' }).click();
  await page.getByRole('radio', { name: /Life scenarios/ }).click();
  await expect(page.getByLabel(/Home price/)).toHaveValue('900');
  await page.setViewportSize({ width: 1280, height: 1100 });
  await page.getByRole('button', { name: /Save scenario snapshot/ }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results-public/scenario.png' });
  await page.getByRole('button', { name: 'Go to compare', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Compare side by side/ })).toBeVisible();
  await expect(page.getByRole('status').filter({ hasText: 'district Seoul Mapo 202609' })).toBeVisible();
  await expect(page.getByRole('article', { name: 'Sunlit House comparison' }).getByRole('listitem').filter({ hasText: 'public demo note' })).toContainText('public demo note');
  await expect(page.getByRole('article', { name: 'Moonlight House comparison' })).not.toContainText('public demo note');
  await page.getByRole('heading', { name: /Compare side by side/ }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results-public/compare.png' });
  const dlP = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save record JSON', exact: true }).click();
  const dl = await dlP;
  const fp = await dl.path();
  const buf = fs.readFileSync(fp as string);
  const rawText = buf.toString('utf-8');
  expect(rawText).toContain('public demo note');
  const parsed = JSON.parse(rawText) as { housing?: { region?: { name?: string; lawd_cd?: string }; month?: string; asset?: string; scenarios?: { homeId?: string; input?: { priceM?: number } }[] }; observations?: { text?: string }[] };
  expect(parsed.housing?.region?.name).toBe('Seoul Mapo');
  expect(parsed.housing?.region?.lawd_cd).toBe('11440');
  expect(parsed.housing?.month).toBe('202609');
  expect(typeof parsed.housing?.asset === 'string' && (parsed.housing?.asset as string).length > 0).toBe(true);
  expect(Array.isArray(parsed.observations) && (parsed.observations as { text?: string }[]).length > 0).toBe(true);
  expect((parsed.observations ?? []).some((o) => (o.text ?? '').includes('public demo note'))).toBe(true);
  const prices = (parsed.housing?.scenarios ?? []).map((s) => s.input?.priceM);
  expect(prices).toContain(900);
  expect(prices).toContain(800);
  expect((parsed.housing?.scenarios ?? []).filter((s) => s.homeId === 'demo-a').map((s) => s.input?.priceM)).toContain(900);
  expect((parsed.housing?.scenarios ?? []).filter((s) => s.homeId === 'demo-b').map((s) => s.input?.priceM)).toContain(800);
  page.once('dialog', (d) => void d.accept());
  await page.getByRole('button', { name: 'Clear my notes', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Try a day|Explore a day/ })).toBeVisible();
  const importInput = page.getByLabel(/Import record/).first();
  if (!(await importInput.isVisible())) {
    await page.getByText('Import a saved record').first().click();
  }
  await importInput.setInputFiles({ name: 'session.json', mimeType: 'application/json', buffer: buf });
  await expect(page.getByText('Imported the record.', { exact: true }).first()).toBeVisible();
  await expect(page.getByRole('heading', { name: /Compare side by side/ })).toBeVisible();
  await expect(page.getByRole('article', { name: 'Sunlit House comparison' }).getByRole('listitem').filter({ hasText: 'public demo note' })).toContainText('public demo note');
  await expect(page.getByRole('status').filter({ hasText: 'district Seoul Mapo 202609' })).toBeVisible();
  const afterRaw = await page.evaluate(() => localStorage.getItem('hs-session-v1'));
  expect(typeof afterRaw === 'string' && (afterRaw as string).length > 0).toBe(true);
  expect(afterRaw as string).toContain('public demo note');
  expect(afterRaw as string).toContain('Seoul Mapo');
  const after = JSON.parse(afterRaw as string) as { housing?: { scenarios?: { input?: { priceM?: number } }[] } };
  expect((after.housing?.scenarios ?? []).map((s) => s.input?.priceM)).toContain(900);
  expect((after.housing?.scenarios ?? []).map((s) => s.input?.priceM)).toContain(800);
  await page.setViewportSize({ width: 390, height: 844 });
  const v = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth }));
  expect(v.sw).toBeLessThanOrEqual(v.cw + 1);
  expect(museCalls.length).toBe(0);
  expect(errors.join('\n')).toBe('');
});
