test('invalid urls and strict invalid import never mutate', async ({ page }) => {
  await fresh(page);
  await page.getByRole('button', { name: '가상 예시로 체험', exact: true }).click();
  await page.getByLabel('관찰 내용', { exact: true }).fill('밝음');
  await page.getByLabel('출처 URL', { exact: true }).fill('ftp://evil');
  await page.getByRole('button', { name: '기록 추가', exact: true }).click();
  await expect(page.getByText(/http\(s\)/)).toBeVisible();
  await page.getByRole('button', { name: '정리·비교로', exact: true }).click();
  const before = await page.evaluate(() => localStorage.getItem('hs-session-v1'));
  const bad = Buffer.from('{oops', 'utf-8');
  page.on('dialog', (d) => void d.dismiss());
  await page.getByLabel(/기록 가져오기/).first().setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: bad });
  await expect(page.getByText(/가져오기 실패/)).toBeVisible();
  const after = await page.evaluate(() => localStorage.getItem('hs-session-v1'));
  expect(after).toBe(before);
});
test('export clear import keeps original flow', async ({ page }) => {
  await fresh(page);
  page.on('dialog', (d) => void d.accept());
  await page.getByRole('button', { name: '가상 예시로 체험', exact: true }).click();
  await expect(page.getByRole('heading', { name: /세 곳을 둘러보고 적습니다/ })).toBeVisible();
  await page.getByLabel('관찰 내용', { exact: true }).fill('원본 기록');
  await page.getByRole('button', { name: '기록 추가', exact: true }).click();
  await page.getByRole('button', { name: '정리·비교로', exact: true }).click();
  await expect(page.getByRole('heading', { name: /두 집을 나란히 놓고 봅니다/ })).toBeVisible();
  const downloadP = page.waitForEvent('download');
  await page.getByRole('button', { name: '기록 JSON 저장', exact: true }).click();
  const dl = await downloadP;
  const fpath = await dl.path();
  const buf = fs.readFileSync(fpath as string);
  expect(buf.toString('utf-8')).toContain('원본 기록');
  await page.getByRole('button', { name: '내 기록 지우기', exact: true }).click();
  await expect(page.getByRole('heading', { name: /어떤 집을 볼까요/ })).toBeVisible();
  await page.getByLabel(/기록 가져오기/).first().setInputFiles({ name: 'session.json', mimeType: 'application/json', buffer: buf });
  await expect(page.getByText('기록을 가져왔습니다.', { exact: true }).first()).toBeVisible();
  await expect(page.getByRole('heading', { name: /두 집을 나란히 놓고 봅니다/ })).toBeVisible();
  await expect(page.getByRole('article', { name: '해뜰집 비교', exact: true })).toContainText('원본 기록');
  await expect(page.getByRole('article', { name: '달빛집 비교', exact: true })).not.toContainText('원본 기록');
});
