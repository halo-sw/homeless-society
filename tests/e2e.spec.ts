async function fresh(page: import('@playwright/test').Page) {
  await page.route('/api/muse/questions', (r) => r.fulfill({ status: 501, contentType: 'application/json', body: JSON.stringify({ error: 'Before AI connection' }) }));
  await page.route('/api/muse/status', (r) => r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ aiReady: false, note: 'Before AI connection', calls: 0, cap: 0 }) }));
  await page.goto('/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
}
async function noOverflow(page: import('@playwright/test').Page) {
  const v = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth }));
  expect(v.sw, 'no horizontal overflow').toBeLessThanOrEqual(v.cw + 1);
}
