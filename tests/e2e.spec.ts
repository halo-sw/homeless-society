test('invalid urls and strict invalid import never mutate', async ({ page }) => {
  await fresh(page);
  await page.getByRole('button', { name: 'Enter simulation', exact: true }).click();
  await page.getByLabel('Observation', { exact: true }).fill('bright');
  await page.getByLabel('Source URL', { exact: true }).fill('ftp://evil');
  await page.getByRole('button', { name: 'Add note', exact: true }).click();
  await expect(page.getByText(/http\(s\)/)).toBeVisible();
  await page.getByRole('button', { name: 'Go to compare', exact: true }).click();
  const before = await page.evaluate(() => localStorage.getItem('hs-session-v1'));
  const bad = Buffer.from('{oops', 'utf-8');
  page.on('dialog', (d) => void d.dismiss());
  await page.getByLabel(/Import record/).first().setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: bad });
  await expect(page.getByText(/Import failed/)).toBeVisible();
  const after = await page.evaluate(() => localStorage.getItem('hs-session-v1'));
  expect(after).toBe(before);
});
test('export clear import keeps original flow', async ({ page }) => {
  await fresh(page);
  page.on('dialog', (d) => void d.accept());
  await page.getByRole('button', { name: 'Enter simulation', exact: true }).click();
  await page.getByLabel('Observation', { exact: true }).fill('original note');
  await page.getByRole('button', { name: 'Add note', exact: true }).click();
  await page.getByRole('radio', { name: /Life scenarios/ }).click();
  await page.getByLabel('Home price (KRW million)').fill('901');
  await page.getByRole('button', { name: /Save scenario snapshot/ }).click();
  await page.getByRole('button', { name: 'Go to compare', exact: true }).click();
  const downloadP = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save record JSON', exact: true }).click();
  const dl = await downloadP;
  const fpath = await dl.path();
  const buf = fs.readFileSync(fpath as string);
  expect(buf.toString('utf-8')).toContain('original note');
  expect(buf.toString('utf-8')).toContain('901');
  await page.getByRole('button', { name: 'Clear my notes', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Try a day|Explore a day/ })).toBeVisible();
  await page.getByLabel(/Import record/).first().setInputFiles({ name: 'session.json', mimeType: 'application/json', buffer: buf });
  await expect(page.getByText('Imported the record.', { exact: true }).first()).toBeVisible();
  await expect(page.getByRole('heading', { name: /Compare side by side/ })).toBeVisible();
});
